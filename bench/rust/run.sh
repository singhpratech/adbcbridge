#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Run the Rust benchmark against one or more databases and record the results in
# bench/RUST_BENCHMARKS.md.
#
#     export ADBC_ODBC_DRIVER=$PWD/build/libadbc_driver_odbc.so
#     export POSTGRES_ODBC_DRIVER=... MSSQL_ODBC_DRIVER=...   # as tests/compat
#     bench/rust/run.sh postgres mssql sqlite
#
# Each database's connection string comes from bench/rust/conn.py, which reads it
# out of tests/compat/test_matrix.py exactly as bench/matrix_bench.py does, so the
# two benchmarks talk to the same servers with the same settings.  Set
# ADBC_MATRIX_SUFFIX to isolate concurrent runs sharing a server.
#
# Knobs: ROWS, FETCH_ROWS, REPS, PYTHON, and the usual CARGO_TARGET_DIR.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="$ROOT/bench/RUST_BENCHMARKS.md"

ROWS="${ROWS:-10000}"
FETCH_ROWS="${FETCH_ROWS:-100000}"
REPS="${REPS:-3}"
PYTHON="${PYTHON:-python3}"

if [ $# -eq 0 ]; then
    echo "usage: $0 <dbname> [dbname ...]" >&2
    exit 2
fi
: "${ADBC_ODBC_DRIVER:?set it to the built libadbc_driver_odbc.so}"

cargo build --release --manifest-path "$HERE/Cargo.toml"
BIN="${CARGO_TARGET_DIR:-$HERE/target}/release/bench_rs"

header() {
    cat <<EOF
<!-- SPDX-License-Identifier: Apache-2.0 -->
# Per-database benchmarks, from Rust

Generated by \`bench/rust/run.sh\` (see \`bench/rust/src/main.rs\`) on $(date +%F).
Table \`(id int32, val float64, txt "row-%012d" utf8, dt date32)\`, one database per
run, every number the median of $REPS timings after a warmup. All rates are rows/s;
higher is better.

| Column | What it measures |
|---|---|
| **ADBC ingest** | $(printf "%'d" "$ROWS") rows through \`libadbc_driver_odbc.so\` and the Rust ADBC driver manager: bulk ingest in \`create\` mode, autocommit off, one commit, DDL + data + commit timed together and the row count verified afterwards. |
| **odbc-api ingest** | the same rows through the [\`odbc-api\`](https://crates.io/crates/odbc-api) crate: a prepared \`INSERT ... VALUES (?, ?, ?, ?)\` with array-bound parameters (\`ColumnarBulkInserter\`, 8192 rows per execute), autocommit off, one commit. The table is created by an empty ADBC ingest first, so both paths write into identical DDL. |
| **Ingest ×** | ADBC ingest over odbc-api ingest. |
| **ADBC fetch** | \`SELECT id, val, txt, dt\` of $(printf "%'d" "$FETCH_ROWS") rows drained into Arrow \`RecordBatch\`es through the bridge. |
| **odbc-api fetch** | the same \`SELECT\` read straight from the ODBC driver into a column-wise row-set buffer (\`ColumnarDynBuffer\`, 8192 rows), no Arrow — the raw ODBC floor for this read. |
| **arrow-odbc fetch** | the same \`SELECT\` through the [\`arrow-odbc\`](https://crates.io/crates/arrow-odbc) crate's \`OdbcReaderBuilder\`, which builds Arrow \`RecordBatch\`es from those same ODBC buffers. |
| **Fetch ×** | ADBC fetch over odbc-api fetch. |

Native delegation is switched off (\`adbc.odbc.delegate=never\`), so every row really
travels over ODBC. Servers run locally in Docker, so the numbers reflect the ODBC
driver plus the database, not a network — and they move with whatever else is running
on the host, so read them as ratios rather than absolutes.

A \`—\` is a step that did not finish; \`bench_rs\` prints the reason on stderr. The one
that is not transient is **arrow-odbc on Db2**: the \`clidriver\` \`libdb2.so\` is built
with a 32-bit \`SQLLEN\`, which makes \`odbc-api\` panic when it describes a column
(IBM's 64-bit \`libdb2o.so\` ships without its dependent libraries here, so it cannot
stand in). The bridge detects that layout itself — \`adbc.odbc.sqllen_32bit\` — and
reads the same result set fine. MySQL Connector/ODBC needs the same
\`LD_PRELOAD=/lib/x86_64-linux-gnu/libstdc++.so.6\` the compat matrix documents in
[\`tests/compat/README.md\`](../tests/compat/README.md).

| Database | ADBC ingest | odbc-api ingest | Ingest × | ADBC fetch | odbc-api fetch | arrow-odbc fetch | Fetch × |
|---|---:|---:|---:|---:|---:|---:|---:|
EOF
}

if [ ! -s "$OUT" ] || ! grep -q '^| Database |' "$OUT"; then
    header > "$OUT"
fi

for db in "$@"; do
    echo "== $db" >&2
    eval "$("$PYTHON" "$HERE/conn.py" "$db")"
    if ! output="$("$BIN" --rows "$ROWS" --fetch-rows "$FETCH_ROWS" --reps "$REPS" "$db")"; then
        echo "$db: bench_rs failed" >&2
        continue
    fi
    echo "$output"
    row="$(printf '%s\n' "$output" | grep '^| ' | tail -1)"
    [ -n "$row" ] || continue
    # One row per database: replace an earlier run of the same one in place.
    tmp="$(mktemp)"
    grep -v "^| $db (" "$OUT" > "$tmp"
    printf '%s\n' "$row" >> "$tmp"
    mv "$tmp" "$OUT"
done

echo "wrote $OUT" >&2
